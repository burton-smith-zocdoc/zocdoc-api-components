import { getCollection, type CollectionEntry } from 'astro:content';
import { buildCatalog } from '../../../tools/api-reference/src/index.ts';
import type { Package } from '../../../tools/cem-agent-docs/src/index.ts';
import { convertBody } from '../../../tools/site-agent-docs/src/convert.ts';
import type { LlmsPage, LlmsSite } from '../../../tools/site-agent-docs/src/llms.ts';
import apiManifest from '../../api-components/custom-elements.json';
import primitivesManifest from '../../primitives/custom-elements.json';
import { version } from '../../api-components/package.json';
import { sidebar } from './sidebar.mjs';

/**
 * The site as markdown for agents: one `.md` per page, `llms.txt`, and `llms-full.txt`. The pages
 * go through the converter that builds each package's `agent-docs/`, so the two never disagree.
 */

const BASE = import.meta.env.BASE_URL.replace(/\/$/, '');
const ORIGIN = `${import.meta.env.SITE}${BASE}`;

type Entry = CollectionEntry<'docs'>;
type SidebarItem = NonNullable<typeof sidebar>[number];

const catalog = buildCatalog([
  { packageName: '@zocdoc/api-components', manifest: apiManifest as Package },
  { packageName: '@zocdoc/api-primitive-components', manifest: primitivesManifest as Package },
]);

/** Starlight's autogenerate order: `sidebar.order`, then slug. */
function autogenerated(entries: Entry[], directory: string): Entry[] {
  const collator = new Intl.Collator('en');
  return entries
    .filter((e) => e.id.startsWith(`${directory}/`))
    .toSorted(
      (a, b) =>
        (a.data.sidebar.order ?? Number.MAX_VALUE) - (b.data.sidebar.order ?? Number.MAX_VALUE) ||
        collator.compare(a.id, b.id)
    );
}

function sidebarEntries(items: SidebarItem[], entries: Entry[]): Entry[] {
  return items.flatMap((item): Entry[] => {
    const slug = typeof item === 'string' ? item : 'slug' in item ? item.slug : undefined;
    if (slug) {
      const entry = entries.find((e) => e.id === slug);
      if (!entry) throw new Error(`llms: sidebar lists missing page ${slug}`);
      return [entry];
    }
    if (typeof item === 'object' && 'autogenerate' in item) {
      return autogenerated(entries, item.autogenerate.directory);
    }
    if (typeof item === 'object' && 'items' in item) return sidebarEntries(item.items, entries);
    return []; // An external link: nothing to convert.
  });
}

function pageUrl(slug: string, hash = ''): string {
  return `${ORIGIN}/${slug}.md${hash ? `#${hash}` : ''}`;
}

function convert(entry: Entry, slugs: Set<string>): LlmsPage {
  if (entry.body === undefined) throw new Error(`llms: ${entry.id} has no body`);
  const { title, description } = entry.data;
  const markdown = convertBody({ title, description }, entry.body, {
    base: BASE,
    catalog,
    // Absolute, so a link still works once the page is pasted into a prompt or llms-full.txt.
    resolveLink: (path, hash) => {
      const slug = path.replace(/^\/|\/$/g, '');
      return slugs.has(slug) ? { href: pageUrl(slug, hash) } : null;
    },
  });
  return { url: pageUrl(entry.id), title, description, markdown };
}

let site: Promise<LlmsSite> | undefined;

/** Converted once per build, however many routes ask. */
export function loadSite(): Promise<LlmsSite> {
  site ??= getCollection('docs').then((entries) => {
    const groups = (sidebar ?? []).map((group) => {
      if (typeof group !== 'object' || !('items' in group)) {
        throw new Error('llms: expected every top-level sidebar item to be a group');
      }
      return { heading: group.label, entries: sidebarEntries(group.items, entries) };
    });
    const slugs = new Set(groups.flatMap((g) => g.entries.map((e) => e.id)));
    return {
      title: 'Zocdoc API Components',
      summary:
        'Web components for embedding Zocdoc provider search and booking in any web page: ' +
        '`@zocdoc/api-components` (booking components that call the Zocdoc API) and ' +
        '`@zocdoc/api-primitive-components` (UI primitives and theme).',
      notes: [
        `These docs describe the latest release, ${version}. A project with the packages ` +
          'installed should read `node_modules/@zocdoc/api-components/agent-docs/index.md` ' +
          'instead, which matches the installed version.',
        'Without a build step, load the prebuilt bundle and theme from a CDN. The Installation ' +
          'page shows both. To render from data you already have, such as an API or tool ' +
          'result, without the components fetching, see Markup and Supplied Data.',
      ],
      sections: groups.map((g) => ({
        heading: g.heading,
        pages: g.entries.map((e) => convert(e, slugs)),
      })),
    };
  });
  return site;
}

/** Each converted page by its slug, for the per-page `.md` routes. */
export async function loadPages(): Promise<Map<string, LlmsPage>> {
  const { sections } = await loadSite();
  const pages = sections.flatMap((s) => s.pages);
  return new Map(pages.map((p) => [p.url.slice(`${ORIGIN}/`.length, -'.md'.length), p]));
}
